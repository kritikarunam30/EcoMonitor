"""Write config/sources.yaml from docs/SPIKE_FACTS.json (plan Phase 2, task 1). No network.

    python scripts/make_sources.py          # or: make sources

Every asset id, band name and access fact the clients use is copied from what the spike saw.
A band that the spike did not list is an error here, never a guess. Re-run after every spike.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import yaml

from app.settings import REPO_ROOT

FACTS_PATH = REPO_ROOT / "docs" / "SPIKE_FACTS.json"
SOURCES_PATH = REPO_ROOT / "config" / "sources.yaml"

# Wind provider (settings `wind.chain`) -> spike collection key and height in metres.
EE_WIND_PROVIDERS = {
    "era5_100m_ee": ("era5_hourly", 100),
    "gfs_ee": ("gfs", 10),
    "era5_land_10m_ee": ("era5_land_hourly", 10),
}
WIND_BAND = "{component}_component_of_wind_{height}m"  # the band must start with this
ANALYSIS_PROPERTY = re.compile(r"forecast_hours?")  # forecast collections: 0 marks the analysis step
# Bands the clients ask for by role; each is checked against the spike's band list.
S2_CHIP_BANDS = ["B2", "B3", "B4", "B8", "B11", "B12"]
S2_ROLES = {"scl_band": "SCL", "red_band": "B4", "nir_band": "B8"}
S2_CLOUD_PROPERTY = "CLOUDY_PIXEL_PERCENTAGE"
S2_PIXEL_M = 10  # resolution of B2, B3, B4 and B8; the chip is sampled at it
SINGLE_BAND = {"worldcover": "Map", "worldpop": "population", "modis_burned": "BurnDate"}
HEADER = (
    "# Generated by scripts/make_sources.py from docs/SPIKE_FACTS.json (`make sources`). Do not edit by hand:\n"
    "# asset ids, band names and access facts come only from the spike (docs/SPIKE_REPORT.md).\n"
)


def _collection(facts: dict[str, Any], key: str) -> dict[str, Any]:
    collection = facts["collections"].get(key)
    if not collection or not collection.get("ok"):
        raise ValueError(f"collection '{key}' was not confirmed by the spike")
    return collection


def _band(collection: dict[str, Any], band: str) -> str:
    if band not in collection["bands"]:
        raise ValueError(f"band '{band}' is not in the spike's band list of {collection['id']}")
    return band


def build_sources(facts: dict[str, Any]) -> dict[str, Any]:
    """The content of sources.yaml. Raises when the spike did not confirm something a client needs."""
    collections = {
        key: {k: c.get(k) for k in ("id", "scale_m", "latency_days", "latest")}
        for key, c in facts["collections"].items()
        if c.get("ok")
    }

    products = {}
    for name, product in facts["products"].items():
        collection = _collection(facts, product["collection_key"])
        products[name] = {
            "collection": product["collection_key"],
            "id": collection["id"],
            "band": _band(collection, product["band"]),
            "cloud_band": _band(collection, product["cloud_band"]) if product.get("cloud_band") else None,
            "scale_m": product["scale_m"],
            "variable": name.removesuffix("_nrti"),
        }

    wind: dict[str, Any] = {}
    for provider, (key, height) in EE_WIND_PROVIDERS.items():
        collection = _collection(facts, key)
        bands = {
            c: next(
                (b for b in collection["bands"] if b.startswith(WIND_BAND.format(component=c, height=height))), None
            )
            for c in "uv"
        }
        if None in bands.values():
            raise ValueError(f"{collection['id']} has no u/v wind bands at {height} m in the spike's band list")
        wind[provider] = {
            "collection": key,
            "id": collection["id"],
            "u_band": bands["u"],
            "v_band": bands["v"],
            "level": f"{height}m",
            "scale_m": collection["scale_m"],
            "analysis_property": next((p for p in collection.get("props", []) if ANALYSIS_PROPERTY.fullmatch(p)), None),
        }
    cds = facts.get("cds", {})
    if cds.get("access") == "ok":
        u_name, v_name = cds["variables in the file"]
        wind["cds_era5_100m"] = {
            "dataset": cds["dataset"],
            "u_variable": u_name,
            "v_variable": v_name,
            "level": "100m",
            "latency_days": cds["latency (days), at most"],
            "request": json.loads(cds["request that worked"]),
        }

    s2 = _collection(facts, "s2_sr")
    if S2_CLOUD_PROPERTY not in s2.get("props", []):
        raise ValueError(f"{s2['id']} has no image property {S2_CLOUD_PROPERTY} in the spike")
    sentinel2 = {
        "id": s2["id"],
        "chip_bands": [_band(s2, b) for b in S2_CHIP_BANDS],
        **{role: _band(s2, band) for role, band in S2_ROLES.items()},
        "cloud_property": S2_CLOUD_PROPERTY,
        "pixel_m": S2_PIXEL_M,
    }

    out: dict[str, Any] = {
        "spike_run": facts["run"]["started_at"],
        "collections": collections,
        "products": products,
        "wind": wind,
        "s2": sentinel2,
    }
    for key, band in SINGLE_BAND.items():
        collection = _collection(facts, key)
        out[key] = {k: collection.get(k) for k in ("id", "scale_m", "latest")} | {"band": _band(collection, band)}
    out["firms"] = {
        source: {"day_range": entry["day_range"], "available": entry.get("available"), "columns": entry["columns"]}
        for source, entry in facts.get("firms", {}).get("sources", {}).items()
        if entry.get("ok")
    }
    return out


def render(sources: dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump(sources, sort_keys=False, width=120, allow_unicode=True)


def main(facts_path: Path = FACTS_PATH, out_path: Path = SOURCES_PATH) -> None:
    if not facts_path.exists():
        raise SystemExit(f"{facts_path} is missing: run scripts/spike_ee.py first")
    out_path.write_text(render(build_sources(json.loads(facts_path.read_text(encoding="utf-8")))), encoding="utf-8")
    print(f"wrote {out_path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
